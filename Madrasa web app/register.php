function toggleRegPass() {
    var p = document.getElementById('reg_pass');
    var icon = document.getElementById('reg_eye_icon');
    if (p.type === 'password') {
        p.type = 'text';
        icon.classList.remove('fa-eye');
        icon.classList.add('fa-eye-slash');
    } else {
        p.type = 'password';
        icon.classList.remove('fa-eye-slash');
        icon.classList.add('fa-eye');
    }
}

function updatePlanSummary() {
    var select = document.getElementById('planSelect');
    var cycleSelect = document.getElementById('billingCycle');
    if (!select || !cycleSelect) return;

    var cycle = cycleSelect.value;
    var isYearly = (cycle === 'yearly');

    // Update each option in the dropdown to reflect current billing cycle price dynamically
    for (var i = 0; i < select.options.length; i++) {
        var optItem = select.options[i];
        var name = optItem.getAttribute('data-name') || optItem.value;
        var mPrice = parseFloat(optItem.getAttribute('data-monthly')) || 0;
        var yPrice = parseFloat(optItem.getAttribute('data-yearly')) || 0;

        if (mPrice === 0 && yPrice === 0) {
            optItem.textContent = name + ' — مفت آزمائش (14 دن فری ٹرائل)';
        } else if (isYearly) {
            var saving = (mPrice * 12) - yPrice;
            var savingText = (saving > 0) ? ' (2 ماہ رعایت: ' + Number(saving).toLocaleString() + ' روپے بچت)' : '';
            optItem.textContent = name + ' — روپے ' + Number(yPrice).toLocaleString() + ' / سال' + savingText;
        } else {
            optItem.textContent = name + ' — روپے ' + Number(mPrice).toLocaleString() + ' / ماہ';
        }
    }

    var opt = select.options[select.selectedIndex];
    if (!opt) return;

    var titleEl = document.getElementById('selectedPlanTitle');
    var limitsEl = document.getElementById('selectedPlanLimits');
    var optName = opt.getAttribute('data-name') || opt.value;
    var optM = parseFloat(opt.getAttribute('data-monthly')) || 0;
    var optY = parseFloat(opt.getAttribute('data-yearly')) || 0;
    var students = opt.getAttribute('data-students') || '50';
    var classes = opt.getAttribute('data-classes') || '3';
    var teachers = opt.getAttribute('data-teachers') || '4';
    var platforms = opt.getAttribute('data-platforms') || 'تینوں پلیٹ فارمز (ویب + اینڈرائڈ + ونڈوز)';

    var activePrice = isYearly ? optY : optM;
    var cycleLabel = isYearly ? 'سالانہ' : 'ماہانہ';
    var priceText = (activePrice > 0) ? ('روپے ' + Number(activePrice).toLocaleString() + ' / ' + cycleLabel) : 'مفت ٹرائل';

    var discountBadge = '';
    if (isYearly && optM > 0) {
        var diff = (optM * 12) - optY;
        if (diff > 0) {
            discountBadge = ' <span class="badge bg-success bg-opacity-25 text-success border border-success border-opacity-50 px-2 py-1 ms-2"><i class="fas fa-gift me-1"></i> 2 ماہ کی رعایت (روپے ' + Number(diff).toLocaleString() + ' سالانہ بچت)</span>';
        }
    }

    titleEl.innerHTML = '<i class="fas fa-box-open me-1"></i> ' + optName + ' — <span class="text-primary fw-bold">' + priceText + '</span>' + discountBadge;
    limitsEl.innerHTML = '<div class="d-flex flex-column gap-1">' +
        '<div><i class="fas fa-check-circle text-success me-1"></i> <strong>وسائل کی حدود:</strong> ' + students + ' طلبہ، ' + classes + ' کلاسز، ' + teachers + ' اساتذہ و عملہ</div>' +
        '<div><i class="fas fa-laptop-code text-primary me-1"></i> <strong>دستیاب پلیٹ فارمز:</strong> ' + platforms + '</div>' +
        '<div><i class="fas fa-clock text-warning me-1"></i> <strong>ٹرائل مدت:</strong> 14 دن تمام فیچرز مکمل فعال رہیں گے (کوئی پیشگی چارجز نہیں)</div>' +
        '</div>';
}

function checkInternetConnection() {
    var offlineAlert = document.getElementById('offlineAlert');
    if (!offlineAlert) return;
    if (!navigator.onLine) {
        offlineAlert.style.display = 'block';
    } else {
        offlineAlert.style.display = 'none';
    }
}

