/**
 * ڈیٹا بیس سے سالانہ تسلسلی منفرد مدرسہ کوڈ (Institute ID) خودکار جنریٹ کرنے کا فنکشن
 * فارمیٹ: M-{YY}-{Sequence} جیسے M-26-001, M-26-002
 */
function generate_next_institute_code(PDO $pdo) {
    $year2 = date('y'); // e.g. "26"
    $prefix = "M-" . $year2 . "-";
    
    $maxSeq = 0;
    try {
        $stmt = $pdo->prepare("SELECT code FROM tenants WHERE UPPER(code) LIKE ?");
        $stmt->execute([strtoupper($prefix) . '%']);
        $codes = $stmt->fetchAll(PDO::FETCH_COLUMN);
        foreach ($codes as $c) {
            if (preg_match('/^M-\d{2}-(\d+)$/i', trim($c), $m)) {
                $num = (int)$m[1];
                if ($num > $maxSeq) $maxSeq = $num;
            }
        }
    } catch (Throwable $e) {}

    $nextSeq = $maxSeq + 1;
    $candidate = sprintf("M-%s-%03d", $year2, $nextSeq);

    // Collision safety loop
    while (true) {
        $chk = $pdo->prepare("SELECT COUNT(*) FROM tenants WHERE UPPER(code) = ?");
        $chk->execute([strtoupper($candidate)]);
        if ((int)$chk->fetchColumn() === 0) {
            break;
        }
        $nextSeq++;
        $candidate = sprintf("M-%s-%03d", $year2, $nextSeq);
    }
    return $candidate;
}

